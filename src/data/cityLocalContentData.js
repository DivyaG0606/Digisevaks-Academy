/**
 * Returns unique local content for a given city slug or key
 */
export function getCityLocalContent(slugKey) {
  if (!slugKey) return null;

  const normalized = slugKey
    .toLowerCase()
    .replace(/^digital-marketing-courses-in-/, '')
    .replace(/^digital-marketing-course-in-/, '')
    .replace(/-pune$/, '');

  if (cityLocalContent[normalized]) {
    return cityLocalContent[normalized];
  }

  // Check alias mappings
  if (normalized === 'pcmc' || normalized === 'pimpri-chinchwad' || normalized === 'thergaon-pcmc') {
    return cityLocalContent['pcmc'];
  }
  if (normalized === 'karve-nagar' || normalized === 'karve-nagar-pune') {
    return cityLocalContent['karve-nagar'];
  }
  if (normalized === 'kothrud' || normalized === 'kothrud-pune') {
    return cityLocalContent['kothrud'];
  }

  return null;
}
